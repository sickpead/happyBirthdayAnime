import type { CakeCandlePosition } from './cake';
import type { ModalId } from './modal';

/**
 * Стадия сцены Desk. Картинки одного и того же сада, всё ближе к столу:
 * `wide` — общий план, `medium` — дворик, `close` — дом и столик вплотную,
 * `empty` — пустой стол крупным планом (сейчас финал сцены), `hub` — стол с предметами.
 */
export type DeskStageId = 'wide' | 'medium' | 'close' | 'empty' | 'hub';

/**
 * Как совершается переход В стадию из предыдущей:
 * `video-transition` — поверх текущей картинки проигрывается ролик, снятый между кадрами
 * стадий, и на его последнем кадре появляется картинка новой стадии;
 * `crossfade` — картинки плавно перетекают одна в другую;
 * `dark-fade` — экран темнеет, картинка подменяется, затемнение уходит;
 * `clouds` — облака закрывают экран и расходятся (сейчас в сцене не используется).
 */
export type DeskTransitionType = 'clouds' | 'dark-fade' | 'crossfade' | 'video-transition';

/** Зум внутри стадии перед переходом к следующей — «камера подъезжает ближе». */
export interface DeskStageZoom {
  /** Точка, к которой приближается камера, % ширины картинки (`transform-origin`). */
  originXPercent: number;
  /** То же по вертикали, % высоты картинки. */
  originYPercent: number;
  /** Во сколько раз увеличить картинку (1 — без зума): предел, пока она не начинает мылиться. */
  maxSafeScale: number;
  /** Длительность зума, мс. */
  durationMs: number;
  /** Пауза после появления стадии до начала зума, мс. */
  startDelayMs: number;
}

/** Стадия сцены Desk: картинка, переход в неё и зум внутри неё. */
export interface DeskZoomStage {
  id: DeskStageId;
  /** URL полноэкранной картинки стадии. */
  imageSrc: string;
  /** Как совершается переход В эту стадию из предыдущей (для первой стадии не используется). */
  transitionIn: DeskTransitionType;
  /**
   * Только для `transitionIn: 'video-transition'` — ролик, который проигрывается перед тем,
   * как показать `imageSrc` этой стадии. Без него переход откатывается на перетекание.
   */
  transitionVideoSrc?: string;
  /** Зум внутри стадии перед переходом к следующей — у последней стадии его нет (там интерактив). */
  zoom?: DeskStageZoom;
}

/**
 * Реакция предмета на наведение: приподнять и наклонить, приподнять и повернуть,
 * приподнять и покачивать, просто приподнять; `crossfade-open` — приподнять и «открыть»:
 * картинка закрытого предмета перетекает в `imageSrcOpen`; `tonearm-swing` — сам предмет
 * стоит на месте, а поворачивается только тонарм его составной картинки
 * (см. {@link DeskHubComposedLayers}); `light-candles` — на фитилях загораются огни;
 * `stack-sway` — стопка приподнимается и покачивается, будто верхняя пластинка съезжает.
 */
export type DeskHoverStyle =
  | 'lift-tilt'
  | 'lift-rotate'
  | 'lift-wiggle'
  | 'lift-only'
  | 'crossfade-open'
  | 'tonearm-swing'
  | 'light-candles'
  | 'stack-sway';

/**
 * Размер и сдвиг картинки «открытого» предмета относительно хитбокса — для предметов,
 * уже нарисованных на фоне: оверлей может быть больше хитбокса (открытая книга шире
 * закрытой, у конверта клапан торчит вверх).
 */
export interface DeskHubHoverReveal {
  /** Ширина оверлея, % ширины хитбокса. */
  widthPercent: number;
  /** Высота оверлея, % высоты хитбокса. */
  heightPercent: number;
  /** Сдвиг оверлея, % ширины хитбокса (положительный — вправо). */
  offsetXPercent?: number;
  /** Сдвиг оверлея, % высоты хитбокса (положительный — вниз). */
  offsetYPercent?: number;
}

/**
 * Положение внутреннего слоя составного предмета поверх его базовой картинки — тот же
 * принцип, что у слоёв проигрывателя в сцене Intro: числа подгоняются на глаз под картинки.
 * Слой растянут на всю базовую картинку (`object-fit: contain`), затем сдвигается
 * и масштабируется.
 */
export interface DeskHubLayerTransform {
  /** Масштаб слоя: у пластинки — вокруг центра слоя, у тонарма — вокруг его оси. */
  scale: number;
  /** Сдвиг слоя, % ширины предмета. */
  offsetXPercent: number;
  /** Сдвиг слоя, % высоты предмета. */
  offsetYPercent: number;
}

/**
 * Пластинка составного предмета. Картинка — плоский диск строго сверху, вписанный в квадрат
 * (диаметр равен ширине картинки, центр диска — центр картинки), а в ракурс стола её кладёт
 * сам CSS: наклон и перспектива. Поэтому диск вращается вокруг своей оси, как настоящая
 * пластинка, а не «катится колесом», как было бы с уже нарисованной в перспективе картинкой.
 *
 * Все проценты — от базовой картинки предмета (корпуса), так что их можно снимать прямо
 * по ней в редакторе: X и диаметр — от её ширины, Y — от её высоты.
 */
export interface DeskHubVinylPlacement {
  /** Центр диска, % ширины картинки корпуса. */
  centerXPercent: number;
  /** Центр диска, % высоты картинки корпуса. */
  centerYPercent: number;
  /** Диаметр диска, % ширины картинки корпуса. */
  diameterPercent: number;
  /** Наклон диска от зрителя вокруг горизонтальной оси, градусы (0 — вид строго сверху). */
  tiltDeg: number;
  /** Расстояние до зрителя для этого наклона, px: меньше — сильнее перспектива. */
  perspectivePx: number;
}

/** Составной предмет из нескольких PNG-слоёв поверх базовой `imageSrc` (сейчас — проигрыватель). */
export interface DeskHubComposedLayers {
  /** Картинка пластинки: плоский диск сверху; лежит на платтере и крутится, пока играет музыка. */
  vinylSrc: string;
  /**
   * Картинка тонарма — только если его нет на корпусе. Поворачивается вокруг оси при
   * `hoverStyle: 'tonearm-swing'`.
   */
  tonearmSrc?: string;
  vinyl: DeskHubVinylPlacement;
  tonearm?: DeskHubLayerTransform & {
    /**
     * Точка поворота тонарма, % его собственного слоя (не всего предмета): там, где на
     * картинке тонарма его ось, — основание, которым он стоит на корпусе.
     */
    pivotXPercent: number;
    pivotYPercent: number;
    /** Угол в покое (тонарм на держателе), градусы; положительный — по часовой стрелке. */
    restRotationDeg: number;
    /** Угол при наведении и фокусе (тонарм подведён к пластинке), градусы. */
    hoverRotationDeg: number;
  };
}

/** Предмет на столе в стадии HUB. */
export type DeskHubObjectId =
  | 'cake'
  | 'letter'
  | 'book'
  | 'turntable'
  | 'vinyl-stack'
  | 'rose-vase'
  | 'colored-pencils'
  | 'fountain-pen';

/**
 * Цветокоррекция картинки предмета — чтобы он не выглядел наклейкой поверх фона, а попадал
 * в тёплый закатный свет сцены. Значения по умолчанию — в `src/utils/deskGrounding.ts`.
 *
 * Контактные и падающие тени — отдельный слой, см. `src/constants/deskObjectShadows.ts`.
 */
export interface DeskHubGrounding {
  /** Поворот оттенка картинки, градусы (по умолчанию 0). */
  hueRotateDeg?: number;
  /** Насыщенность картинки, % (по умолчанию 100). */
  saturatePercent?: number;
  /** Яркость картинки, % (по умолчанию 100). */
  brightnessPercent?: number;
}

/**
 * Куда падает тень предмета. Цвет разный: на столешнице — тёплый коричнево-серый,
 * на траве — с зелёным подмесом, на стуле — как на дереве, но мягче.
 */
export type DeskShadowSurface = 'table' | 'grass' | 'chair';

/**
 * Одна силуэтная тень: та же PNG, сдвинутая влево-вниз. Свет сцены — сверху-справа,
 * поэтому `offsetXPercent` только отрицательный, `offsetYPercent` — вниз.
 */
export interface DeskSilhouetteShadow {
  /** Сдвиг по X. Только ≤ 0: ни одна тень не уходит вправо. */
  offsetXPercent: number;
  /** Сдвиг по Y. Только ≥ 0: вниз, как тень стола на траве. */
  offsetYPercent: number;
  /** Размытие силуэта, px. */
  blurPx: number;
  /** Непрозрачность, 0…1. */
  opacity: number;
  /** Растяжение по ширине (1 — как предмет). */
  scaleX?: number;
  /** Растяжение по высоте (1 — как предмет). */
  scaleY?: number;
}

/**
 * Два слоя под предметом: плотный контакт у основания и мягкая падающая влево-вниз.
 * Рисуются копией той же PNG, поэтому тень повторяет форму предмета, а не общий овал.
 */
export interface DeskObjectShadowPlan {
  surface: DeskShadowSurface;
  contact: DeskSilhouetteShadow;
  cast: DeskSilhouetteShadow;
}

/**
 * Где лежит декорация относительно кликабельных предметов: `below` — под ними (ваза,
 * пластинки: они и физически дальше), `above` — поверх (ручка и карандаши лежат на
 * столешнице, а не под книгой). Оба слоя кликов не перехватывают.
 */
export type DeskHubDecorLayer = 'below' | 'above';

/**
 * Декоративный предмет стадии HUB: просто картинка поверх стола — без клика, наведения
 * и модалки. Не перехватывает события.
 */
export interface DeskHubDecorProp {
  id: string;
  /** URL картинки с прозрачным фоном. */
  imageSrc: string;
  /** Центр предмета, % ширины картинки стола (в отличие от кликабельных — там левый край). */
  xPercent: number;
  /** Центр предмета, % высоты картинки стола. */
  yPercent: number;
  /** Ширина предмета, % ширины картинки стола; высота — по пропорциям картинки. */
  widthPercent: number;
  /** Небольшой наклон, градусы (по умолчанию 0): предмет лежит не по сетке. */
  rotateDeg?: number;
  /** Под предметами или поверх них. */
  layer: DeskHubDecorLayer;
}

/** Содержимое модалки одного листа-черновика. У каждого листа своё. */
export interface DeskDraftSheetModal {
  /** Заголовок диалога; он же — его доступное имя. */
  title: string;
  /** Картинки в модалке: неудачные кадры комикса и прочее. Может быть пустым. */
  images: readonly string[];
  /** Подпись под картинками. */
  caption?: string;
}

/** Куда «лёг» лист: на столешницу или в траву. Сейчас только помечает место в конфиге. */
export type DeskDraftSurface = 'table' | 'grass';

/**
 * Лист-черновик стадии HUB: своя кнопка и своя модалка. Листы разбросаны по столу
 * и по траве; координаты — центр листа (как у декора), а не левый верхний угол.
 */
export interface DeskDraftSheet {
  id: string;
  /** Доступное имя кнопки. */
  label: string;
  /** URL картинки листа с прозрачным фоном. */
  imageSrc: string;
  /** Центр листа, % ширины картинки стола. */
  xPercent: number;
  /** Центр листа, % высоты картинки стола. */
  yPercent: number;
  /** Ширина листа, % ширины картинки стола; высота — по пропорциям картинки. */
  widthPercent: number;
  /** Наклон листа, градусы (положительный — по часовой стрелке). */
  rotateDeg: number;
  /** Где лежит лист — на столе или в траве. */
  surface: DeskDraftSurface;
  /** Цветокоррекция картинки. Если не задано — общая (см. `getDraftSheetGrounding`). */
  grounding?: DeskHubGrounding;
  /** Содержимое модалки этого листа. */
  modal: DeskDraftSheetModal;
}

/** Слой-предмет на столе HUB: кнопка с картинкой предмета поверх пустого стола. */
export interface DeskHubObjectLayer {
  id: DeskHubObjectId;
  /** Название предмета — доступное имя кнопки. */
  label: string;
  /**
   * URL картинки предмета с прозрачным фоном. У составного предмета (`layers`) — базовый
   * слой (корпус), который задаёт размер предмета.
   */
  imageSrc: string;
  /**
   * Картинка того же предмета в открытом виде — для `hoverStyle: 'crossfade-open'`:
   * при наведении закрытая картинка перетекает в неё. У предмета на фоне закрытой
   * картинки нет: поверх стола проявляется только эта.
   */
  imageSrcOpen?: string;
  /** Размер оверлея `imageSrcOpen` относительно хитбокса — если предмет нарисован на фоне. */
  hoverReveal?: DeskHubHoverReveal;
  /**
   * Фитили свечей, % хитбокса торта — для `hoverStyle: 'light-candles'`. При наведении
   * на каждом фитиле появляется огонь.
   */
  candles?: readonly CakeCandlePosition[];
  /** Если задано — предмет составной: поверх `imageSrc` лежат пластинка и тонарм. */
  layers?: DeskHubComposedLayers;
  /** Левый край слоя, % ширины картинки стола. */
  xPercent: number;
  /** Верхний край слоя, % высоты картинки стола. */
  yPercent: number;
  /** Ширина слоя, % ширины картинки стола; высота — по пропорциям картинки предмета. */
  widthPercent: number;
  /**
   * Высота слоя, % высоты картинки стола. Нужна, когда предмет уже нарисован на фоне
   * (`paintedInBackdrop`) и своей PNG нет: кнопка не может взять высоту из картинки.
   */
  heightPercent?: number;
  /**
   * Предмет уже есть на картинке стола: кнопка остаётся для клика, но своя PNG
   * поверх не рисуется — иначе предмет задвоится.
   */
  paintedInBackdrop?: boolean;
  /**
   * Постоянный наклон предмета в покое, градусы (по умолчанию 0; положительный — по часовой
   * стрелке): мелкий предмет выглядит случайно упавшим на стол, а не положенным по сетке.
   * Сохраняется при наведении и фокусе у `crossfade-open` — открываясь, предмет не выпрямляется.
   */
  restRotationDeg?: number;
  /**
   * Цветокоррекция картинки предмета (см. `src/utils/deskGrounding.ts`); без этого поля
   * картинка показывается как есть.
   */
  grounding?: DeskHubGrounding;
  /**
   * Явный `z-index`, когда предмет должен лежать поверх соседа независимо от порядка
   * в массиве (карандаши и ручка — поверх книги). По умолчанию порядок задаёт массив.
   */
  zIndexOverride?: number;
  /** Модалка, которая открывается по клику. */
  modalId: ModalId;
  /** Реакция на наведение. */
  hoverStyle: DeskHoverStyle;
}
